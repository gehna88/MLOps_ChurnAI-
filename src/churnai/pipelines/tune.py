"""Hyperparameter search: one Optuna study per model family.

Run with ``make tune`` or ``python -m churnai.pipelines.tune``.

The objective is the same 5-fold CV ROC-AUC that ``make train`` selects on, computed
on the training split only; this pipeline never reads the test split.

Outputs
-------
* MLflow experiment ``churnai-tuning``: a parent run per family, a nested run per trial
* The best params per family, written to ``configs/models.yaml`` as new candidates
* ``reports/tuning.csv`` - the best trial of each family
"""

from __future__ import annotations

import re
import textwrap
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import optuna
import pandas as pd
import yaml
from sklearn.metrics import roc_auc_score

from churnai.config import Settings, load_yaml
from churnai.data import io
from churnai.data.schema import FEATURE_COLUMNS
from churnai.exceptions import ConfigError
from churnai.logging_utils import get_logger
from churnai.models.factory import ModelSpec
from churnai.models.tracking import ExperimentTracker, make_tracker
from churnai.models.training import ModelTrainer
from churnai.pipelines._cli import exit_with, run_cli

logger = get_logger(__name__)

PARAM_DECIMALS = 6
OBJECTIVE_METRIC = "cv_roc_auc"
TUNED_MARKER = "# Generated by `make tune`: everything below this line is overwritten."


@dataclass(frozen=True)
class Study:
    name: str
    estimator: str
    fixed: dict[str, Any]
    space: dict[str, dict[str, Any]]


def load_studies(path: Path) -> tuple[list[Study], int]:
    raw = load_yaml(path)
    studies = [
        Study(s["name"], s["estimator"], s.get("fixed") or {}, s["space"]) for s in raw.get("studies") or []
    ]
    if not studies:
        raise ConfigError(f"No tuning studies defined in {path}")
    return studies, int(raw.get("n_trials", 10))


def suggest(trial: optuna.Trial, space: dict[str, dict[str, Any]]) -> dict[str, Any]:
    params: dict[str, Any] = {}
    for name, dist in space.items():
        kind = dist["type"]
        if kind == "int":
            params[name] = trial.suggest_int(name, dist["low"], dist["high"])
        elif kind == "float":
            params[name] = trial.suggest_float(name, dist["low"], dist["high"], log=dist.get("log", False))
        elif kind == "categorical":
            params[name] = trial.suggest_categorical(name, dist["choices"])
        else:
            raise ConfigError(f"Unknown distribution '{kind}' for parameter '{name}'")
    return params


def _run_study(
    study_cfg: Study, n_trials: int, trainer: ModelTrainer, X: pd.DataFrame, y: pd.Series,
    tracker: ExperimentTracker, seed: int,
) -> dict[str, Any]:
    def objective(trial: optuna.Trial) -> float:
        params = {**study_cfg.fixed, **suggest(trial, study_cfg.space)}
        spec = ModelSpec(study_cfg.name, study_cfg.estimator, params)
        with tracker.run(f"{study_cfg.name}-trial-{trial.number:02d}", nested=True,
                         tags={"estimator": study_cfg.estimator}):
            score = float(roc_auc_score(y, trainer.cv_proba(spec, X, y)))
            tracker.log_params(params)
            tracker.log_metrics({OBJECTIVE_METRIC: score})
        return score

    with tracker.run(f"study-{study_cfg.name}", tags={"estimator": study_cfg.estimator}):
        study = optuna.create_study(direction="maximize", sampler=optuna.samplers.TPESampler(seed=seed))
        study.optimize(objective, n_trials=n_trials)
        best = {k: round(v, PARAM_DECIMALS) if isinstance(v, float) else v
                for k, v in study.best_params.items()}
        tracker.log_params({"n_trials": n_trials, **{f"best_{k}": v for k, v in best.items()}})
        tracker.log_metrics({f"best_{OBJECTIVE_METRIC}": study.best_value})
    logger.info("Study %-14s best cv_roc_auc=%.4f", study_cfg.name, study.best_value)
    return {"name": study_cfg.name, "estimator": study_cfg.estimator,
            OBJECTIVE_METRIC: round(study.best_value, 4), "params": {**study_cfg.fixed, **best}}


def write_candidates(path: Path, tuned: list[dict[str, Any]]) -> None:
    """Regenerate the tuned block at the end of the file; everything above it stays verbatim."""
    hand_written = path.read_text(encoding="utf-8").split(TUNED_MARKER)[0].rstrip()
    added = [{"name": t["name"], "estimator": t["estimator"], "params": t["params"]} for t in tuned]
    match = re.search(r"^( *)- \w+:", hand_written, flags=re.MULTILINE)
    indent = match.group(1) if match else "  "  # stay valid YAML whatever the file's list indent is
    block = textwrap.indent(yaml.safe_dump(added, sort_keys=False), indent)
    path.write_text(f"{hand_written}\n\n{indent}{TUNED_MARKER}\n{block}", encoding="utf-8")


def run(settings: Settings, tracker: ExperimentTracker | None = None) -> pd.DataFrame:
    tracker = tracker or make_tracker(settings, settings.mlflow.tuning_experiment)
    optuna.logging.set_verbosity(optuna.logging.WARNING)
    studies, n_trials = load_studies(settings.resolve(settings.training.tuning_config))

    X, y = io.split_features_target(io.read_csv(settings.train_path))
    X = X[list(FEATURE_COLUMNS)]
    seed = settings.project.random_seed
    trainer = ModelTrainer(settings.training.cv_folds, seed, settings.training.threshold_metric)

    tuned = [_run_study(s, n_trials, trainer, X, y, tracker, seed) for s in studies]
    write_candidates(settings.resolve(settings.training.models_config), tuned)

    summary = pd.DataFrame(tuned)
    reports_dir = settings.resolve(settings.paths.reports_dir)
    reports_dir.mkdir(parents=True, exist_ok=True)
    summary.to_csv(reports_dir / "tuning.csv", index=False)
    return summary


def main() -> None:
    exit_with(run_cli("Search hyperparameters and add the best as model candidates.", run))


if __name__ == "__main__":
    main()
